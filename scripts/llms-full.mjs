#!/usr/bin/env node
// Writes llms-full.txt: the pages a language model needs to answer questions about this tool,
// in one file, in a fixed order, with no clock and nothing typed by hand. llms.txt is the index;
// this is the content. `--check` fails when the committed file is out of date, so it cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCES = [
  "README.md",
  "docs/FAQ.md",
  "docs/PAIN.md",
  "docs/mcp.md",
  "docs/SCORING.md",
  "docs/LANGUAGES.md",
  "docs/MEASUREMENT.md",
  "docs/SARIF.md",
  "bench/PRECISION.md",
  "bench/COMMIT-RULES.md",
  "bench/DASH-DEFAULT.md",
  "CONTRIBUTING.md",
];

export function build() {
  const parts = [
    "# ai-slop-linter, full text",
    "",
    "Generated by `node scripts/llms-full.mjs` from the files named below. Do not edit by hand. The short index is llms.txt.",
  ];
  for (const f of SOURCES) parts.push("", "---", "", `Source: ${f}`, "", readFileSync(join(root, f), "utf8").trimEnd());
  return parts.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, "llms-full.txt");
  const fresh = build();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current !== fresh) {
      console.error("llms-full: llms-full.txt is out of date. Run `node scripts/llms-full.mjs` and commit it.");
      process.exit(1);
    }
    console.log("llms-full: ok");
  } else {
    writeFileSync(target, fresh);
    console.log(`llms-full: wrote llms-full.txt (${fresh.split("\n").length} lines, ${SOURCES.length} sources)`);
  }
}
