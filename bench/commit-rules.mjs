#!/usr/bin/env node
/**
 * Measures the commit-message rules on commit messages people wrote before 2021 and on the
 * model-written ones in bench/corpus, and writes bench/COMMIT-RULES.md.
 *
 *   node bench/commit-rules.mjs     fetch the human sources if needed (network), measure, write the report
 *
 * Not run in CI: it needs network and the clones. test/commit-rules.test.mjs covers the counting.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { candidateRules, commitRules, EXCLUDED, NOT_ADOPTED } from "../dist/src/commits.js";
import { alreadyFlagged, hitsPerRule, splitMachine, tokenHits } from "./commit-rules-lib.mjs";

const root = new URL("..", import.meta.url).pathname;
const { sources } = JSON.parse(readFileSync(join(root, "bench", "commit-human.json"), "utf8"));
const git = (dir, ...args) => execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", maxBuffer: 1 << 28 });

function ensure(src) {
  const dir = join(root, "_upstream", src.id);
  if (existsSync(join(dir, ".git")) && git(dir, "rev-parse", "HEAD").trim() === src.commit) return dir;
  mkdirSync(dir, { recursive: true });
  git(dir, "init");
  git(dir, "fetch", "--depth", String(src.tuning + src.holdout + 500), src.repo, src.commit);
  git(dir, "checkout", "FETCH_HEAD");
  if (git(dir, "rev-parse", "HEAD").trim() !== src.commit) throw new Error(`${src.id}: fetched a different commit than ${src.commit}`);
  return dir;
}

/** `n` non-merge commit messages after skipping `skip`, newest first. */
function messages(dir, skip, n) {
  return git(dir, "log", "--no-merges", `--skip=${skip}`, `-n`, String(n), "--format=%B%x00")
    .split("\0")
    .map((m) => m.trim())
    .filter(Boolean);
}

const sets = sources.map((src) => {
  const dir = ensure(src);
  return { src, tuning: messages(dir, 0, src.tuning), holdout: messages(dir, src.tuning, src.holdout) };
});
const machine = splitMachine(readFileSync(join(root, "bench", "corpus", "machine", "commit-messages.md"), "utf8"));

const tuningHits = sets.map((s) => hitsPerRule(s.tuning, candidateRules));
const holdoutHits = sets.map((s) => hitsPerRule(s.holdout, candidateRules));
const machineHits = hitsPerRule(machine, candidateRules);
const leftOut = sets.map((s) => tokenHits(s.tuning));

const rows = candidateRules.map((r) => {
  const flagged = alreadyFlagged(r.id);
  const decision = r.id in NOT_ADOPTED ? `not adopted: ${NOT_ADOPTED[r.id]}` : "adopted";
  const dropped = (EXCLUDED[r.id] ?? []).length;
  const tokens = flagged.total ? `${flagged.total - dropped} of ${flagged.total}` : "regex";
  return `| \`${r.id}\` | ${tokens} | ${tuningHits.map((h) => h[r.id]).join(" / ")} | ${holdoutHits.map((h) => h[r.id]).join(" / ")} | ${machineHits[r.id]} of ${machine.length} | ${flagged.total ? `${flagged.flagged} of ${flagged.total}` : "n/a"} | ${decision} |`;
});

const tokenLines = Object.keys(EXCLUDED).flatMap((id) => {
  const counts = new Map();
  for (const per of leftOut) for (const t of per[id] ?? []) counts.set(t.token, (counts.get(t.token) ?? 0) + t.messages);
  return EXCLUDED[id].map((token) => `| \`${id}\` | \`${token}\` | ${counts.get(token) ?? 0} |`);
});

const md = `# Commit-message rules measured on human commits

Generated by \`node bench/commit-rules.mjs\`. Do not edit by hand.

The rules in \`src/commits.ts\` use phrase lists adapted from [tbhb/vale-ai-tells](https://github.com/tbhb/vale-ai-tells) (MIT), as \`src/commit-phrases.ts\` states. A list written for another tool is only useful here if it stays quiet on commit messages people wrote, so each rule was run on commits from before 2021.

## Method

| source | tag | commit | licence | tuning messages | held-out messages |
|---|---|---|---|---:|---:|
${sets.map((s) => `| [${s.src.id}](${s.src.repo}) | ${s.src.tag} | \`${s.src.commit.slice(0, 12)}\` | ${s.src.licence} | ${s.tuning.length} | ${s.holdout.length} |`).join("\n")}

Messages are read from shallow clones in \`_upstream/\` and are not copied into this repository. The tuning messages are the newest ones before the tag; a phrase that matched any of them was left out. The held-out messages are the next ones back in time. They were not used to choose phrases, so their hit count is the honest estimate: after tuning, the tuning count is zero by construction and says nothing about unseen text.

A rule was adopted when it had no hit on the tuning messages after the left-out phrases were removed, at most one hit across the held-out messages of all sources, and at least ten phrases remaining (a regular expression rule is judged on hits alone). The model column counts the ${machine.length} commit messages in \`bench/corpus/machine/commit-messages.md\`.

## Per rule

Hits are messages with at least one finding, listed per source in the order ${sets.map((s) => s.src.id).join(", ")}.

| rule | phrases kept | tuning hits | held-out hits | model messages | phrases the prose rules already flag | decision |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Phrases left out

| rule | phrase | tuning messages it matched |
|---|---|---:|
${tokenLines.join("\n") || "| | none | |"}

## What this does not show

- Two projects, both BSD-licensed Python, both with strong commit conventions. A project with another habit, or a person writing "This commit fixes ..." on purpose, will see findings. That is why these are warnings and can be switched off with \`--ignore\`.
- The model sample is ${machine.length} messages written for this repository. It shows the rules fire on that kind of text, not how often they fire on all model output.
`;
writeFileSync(join(root, "bench", "COMMIT-RULES.md"), md);
console.log(`wrote bench/COMMIT-RULES.md; adopted ${commitRules.length} of ${candidateRules.length}`);
for (const r of candidateRules) console.log(`${r.id}: tuning ${tuningHits.map((h) => h[r.id])} held-out ${holdoutHits.map((h) => h[r.id])} model ${machineHits[r.id]}`);
