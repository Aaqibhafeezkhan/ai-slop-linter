// The measurement behind the question "should `dash` fail the build by default?". Pure functions
// over a corpus directory, so a test can run them on a three-file corpus.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { GRADE_FLOOR, WEIGHTS, lintText } from "../dist/src/index.js";

/** The default --max-score, and the stricter one this repository sets for its own Markdown. */
export const LIMITS = [10, 3];
/** Dashes per 1,000 words at or above which a file would still carry the error, for the threshold option. */
export const THRESHOLDS = [0.5, 1, 2, 3, 5, 10];
export const POLICIES = [
  { id: "error", label: "every dash is an error (before this decision)" },
  { id: "split", label: "em and en dash are errors, ASCII ` - ` and `--` are warnings (today)" },
  { id: "warning", label: "every dash is a warning" },
  { id: "off", label: "dash is off" },
];

const round1 = (n) => Math.round(n * 10) / 10;

/** The two dash messages that are plain ASCII. Everything else the rule reports is a real em or en dash. */
export const isAscii = (f) => f.message === "spaced hyphen used as a dash" || f.message === "double hyphen used as a dash";

/**
 * What the CLI would conclude about a file if `dash` had another severity. Mirrors lintDoc: weights
 * per severity, the denominator clamped at GRADE_FLOOR words, no score under the floor. "split" is
 * the severity the linter reports itself, so it changes nothing.
 */
export function reassess(result, policy) {
  const findings = result.findings
    .filter((f) => !(policy === "off" && f.rule === "dash"))
    .map((f) => (f.rule !== "dash" ? f : policy === "warning" ? { ...f, severity: "warning" } : policy === "error" ? { ...f, severity: "error" } : f));
  const weighted = findings.reduce((s, f) => s + WEIGHTS[f.severity], 0);
  const score = result.words < GRADE_FLOOR ? null : round1(weighted / (Math.max(result.words, GRADE_FLOOR) / 1000));
  return { findings: findings.length, errors: findings.filter((f) => f.severity === "error").length, score };
}

/** The CLI's own failing test: an error-severity finding, or a score above the limit. */
export const fails = (assessed, max) => assessed.errors > 0 || (assessed.score !== null && assessed.score > max);

export function readGroup(corpus, group) {
  const dir = join(corpus, group);
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => ({ name: `${group}/${f}`, result: lintText(`${group}/${f}`, readFileSync(join(dir, f), "utf8")) }));
}

export function measure(corpus) {
  const groups = { human: readGroup(corpus, "human"), machine: readGroup(corpus, "machine") };
  const policies = POLICIES.map((p) => ({
    ...p,
    sets: Object.fromEntries(
      Object.entries(groups).map(([group, files]) => [
        group,
        Object.fromEntries(LIMITS.map((max) => [String(max), { total: files.length, failing: files.filter((f) => fails(reassess(f.result, p.id), max)).map((f) => f.name) }])),
      ]),
    ),
  }));
  const dashes = Object.fromEntries(
    Object.entries(groups).map(([group, files]) => [
      group,
      files.map(({ name, result }) => {
        const count = result.findings.filter((f) => f.rule === "dash").length;
        const ascii = result.findings.filter((f) => f.rule === "dash" && isAscii(f)).length;
        return { name, words: result.words, dashes: count, ascii, per1k: result.words ? round1(count / (result.words / 1000)) : 0 };
      }),
    ]),
  );
  const sweep = THRESHOLDS.map((threshold) => ({ threshold, human: dashes.human.filter((d) => d.per1k >= threshold).length, machine: dashes.machine.filter((d) => d.per1k >= threshold).length }));
  return { policies, dashes, sweep };
}

const cell = (s) => `${s.failing.length} of ${s.total}`;

export function render(data) {
  const l = [];
  l.push("# Should `dash` fail the build by default?");
  l.push("");
  l.push("Generated by `node bench/dash.mjs`. Do not edit by hand; CI fails when this file does not match a fresh run.");
  l.push("");
  l.push("## The question");
  l.push("");
  l.push("`dash` used to report every dash as an `error`, so one dash in a file failed the run (exit 1) whatever the rest of the file looked like. The topic is contested: readers argue that people have always used the em dash. This file measures what each alternative does on the committed corpus (`bench/corpus`), nothing more.");
  l.push("");
  l.push("## Files that fail, by policy");
  l.push("");
  l.push(`A file fails when it has an error-severity finding or its score is above the limit. Limit ${LIMITS[0]} is the default; ${LIMITS[1]} is what this repository sets in \`.slop.json\`.`);
  l.push("");
  l.push(`| policy | human, limit ${LIMITS[0]} | machine, limit ${LIMITS[0]} | human, limit ${LIMITS[1]} | machine, limit ${LIMITS[1]} |`);
  l.push("|---|---|---|---|---|");
  for (const p of data.policies) l.push(`| ${p.label} | ${cell(p.sets.human[LIMITS[0]])} | ${cell(p.sets.machine[LIMITS[0]])} | ${cell(p.sets.human[LIMITS[1]])} | ${cell(p.sets.machine[LIMITS[1]])} |`);
  l.push("");
  l.push("Human files are texts written before 2021. Machine files are unedited model output. Lower is better for the first and third columns; higher is better for the second and fourth, if failing on model output is what you want.");
  l.push("");
  const before = data.policies[0];
  l.push("Under the earlier policy (every dash an error) these human files failed at the default limit:");
  l.push("");
  const humanFails = before.sets.human[LIMITS[0]].failing;
  l.push(humanFails.length ? humanFails.map((n) => `- \`${n}\``).join("\n") : "- none");
  l.push("");
  l.push("## Dashes per file");
  l.push("");
  l.push("| file | words | dashes | of which ASCII | per 1,000 words |");
  l.push("|---|---:|---:|---:|---:|");
  for (const d of [...data.dashes.human, ...data.dashes.machine]) l.push(`| \`${d.name}\` | ${d.words} | ${d.dashes} | ${d.ascii} | ${d.per1k} |`);
  l.push("");
  l.push("## Option: error only above a density");
  l.push("");
  l.push("Files at or above each density of dashes per 1,000 words, which is the set that would keep the error if the rule only fired from that density up:");
  l.push("");
  l.push("| dashes per 1,000 words | human files | machine files |");
  l.push("|---:|---:|---:|");
  for (const s of data.sweep) l.push(`| ${s.threshold} | ${s.human} | ${s.machine} |`);
  l.push("");
  l.push("## What this does not show");
  l.push("");
  l.push(`- ${data.dashes.human.length} human files and ${data.dashes.machine.length} model files. Some of the human files are more than a century and a half old, and none is a modern README.`);
  l.push("- It does not measure how readers react. Whether a failing build over one dash costs more goodwill than it saves is a judgement about people, not a number here.");
  l.push("- It does not say a file was written by a model. It counts a character.");
  l.push("");
  l.push("## Decision");
  l.push("");
  l.push("Decided on 2 November 2026: a real em dash (U+2014) or en dash used as a dash stays an `error`, so it still fails a run. A spaced ASCII hyphen (` - `) or a double hyphen (`--`) is a `warning`: it counts towards the score and fails a file only when the score is above the limit.");
  l.push("");
  l.push("Reason: on public READMEs written before 2021, most ASCII hits were a name followed by a tagline or a key followed by its action, which people wrote long before models did. The real em dash remains the tell the rule was written for.");
  l.push("");
  l.push("This is a choice made on the evidence above, not a claim that the question is settled for readers. The corpus is small (see above), and the choice can be reversed in `src/rules/dashes.ts`. If the error is unwelcome in your repository, turn the rule off with `--ignore dash`.");
  l.push("");
  return l.join("\n");
}
