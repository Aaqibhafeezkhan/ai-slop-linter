#!/usr/bin/env node
/**
 * Measures every registered language pack on the human and machine corpora of its language,
 * and writes bench/PACKS.md.
 *
 *   node bench/packs.mjs           regenerate the table
 *   node bench/packs.mjs --check   fail if the committed table is stale
 *
 * Rates are findings per 1,000 words, the same measure bench/precision.mjs uses. The shipping
 * limit that decides which rules may ship is in bench/packs-lib.mjs and is enforced by
 * test/packs.test.mjs for every pack.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { languageRules } from "../dist/src/index.js";
import { corpusFor, measure, MIN_HUMAN_WORDS, MIN_MACHINE_WORDS, wordsIn } from "./packs-lib.mjs";

const root = new URL("..", import.meta.url).pathname;
const output = join(root, "bench", "PACKS.md");

/** The languages whose corpora are measured even before a pack exists for them. */
const CORPUS_LANGS = ["de", "es", "fr"];
const NAMES = { de: "German", en: "English", es: "Spanish", fr: "French" };
const name = (lang) => NAMES[lang] ?? lang;
const languages = [...new Set([...CORPUS_LANGS, ...Object.keys(languageRules)])].sort();

const per1k = (n, words) => (words ? Math.round((n / (words / 1000)) * 10) / 10 : 0);
const n0 = (n) => n.toLocaleString("en-US");

const sizes = languages.map((lang) => {
  const { human, machine } = corpusFor(lang);
  return { lang, human, machine, hw: wordsIn(human), mw: wordsIn(machine) };
});

const sections = sizes.map((row) => {
  const pack = languageRules[row.lang];
  if (!pack) {
    return `### ${name(row.lang)} (\`${row.lang}\`)

No pack is registered for ${name(row.lang)} yet. Corpus: ${row.human.length} human files, ${n0(row.hw)} words;
${row.machine.length} machine files, ${n0(row.mw)} words. Rules are measured here once a pack lands.`;
  }
  const h = measure(pack, row.human);
  const m = measure(pack, row.machine);
  const table = pack
    .map((rule) => {
      const hs = h.perRule.get(rule.id);
      const ms = m.perRule.get(rule.id);
      return `| \`${rule.id}\` | ${rule.severity} | ${per1k(hs.total, h.words)} | ${per1k(ms.total, m.words)} | ${hs.files} |`;
    })
    .join("\n");
  return `### ${name(row.lang)} (\`${row.lang}\`)

Human corpus ${n0(h.words)} words in ${row.human.length} files; machine corpus ${n0(m.words)} words in ${row.machine.length} files.

| rule | severity | human /1k | machine /1k | human files hit |
|---|---|---:|---:|---:|
${table}`;
});

const corpusTable = sizes
  .map((s) => `| ${name(s.lang)} (\`${s.lang}\`) | ${s.human.length} | ${n0(s.hw)} | ${s.machine.length} | ${n0(s.mw)} |`)
  .join("\n");

const packCount = Object.keys(languageRules).length;

const md = `# Language packs measured on their own language

Generated by \`node bench/packs.mjs\`. Do not edit by hand; CI fails when this
file does not match a fresh run.

## Method

A language pack is a set of rules that runs only on text in its language. A file switches a
pack on when the file's effective language is that language: declared, in its front matter, or
detected from the prose. A file in another language runs the pack on any paragraph detected as
that language. English files are unchanged.

Two kinds of corpus are measured for each language, and they differ in what they can show.

- Human text is prose from Project Gutenberg and the \`bench/typography\` excerpts. Both
  predate language models, so nothing in them can carry a habit learned from one. The Wikipedia
  articles in the human corpus are modern, edited within the past year, and cannot be verified
  as free of model-assisted editing, so they are the weakest part of it. Provenance, licences
  and revision ids for every file are in \`bench/packs/MANIFEST.md\`.
- Machine text is unedited model output under \`bench/packs/machine/<lang>/\`, written from
  the prompts and model recorded in \`bench/packs/MANIFEST.md\`.

Each rule is called directly on each file's text, without a declared language, so a pack is
measured whether or not it is registered. Rates are findings per 1,000 words.

The shipping limit decides which rules may ship. A pack rule ships only if:

- it produces **zero** findings on every human file of its language, and
- it produces **at least one** finding on the machine corpus of that language, and
- both corpora are large enough to measure against: every file carries words, the human corpus
  has at least ${MIN_HUMAN_WORDS} words in total, and the machine corpus has at least ${MIN_MACHINE_WORDS}.

\`test/packs.test.mjs\` enforces the limit for every registered pack by reading the same corpora,
and fails when a rule breaks it.

What the numbers are not: they are not detection accuracy, and a human corpus of this size
cannot establish that a rule is never wrong. A high machine rate shows that a rule matches what
the measured model output looks like, not what every model produces.

## Corpus sizes

| language | human files | human words | machine files | machine words |
|---|---:|---:|---:|---:|
${corpusTable}

Packs registered: ${packCount}.

## Per language

${sections.join("\n\n")}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== md) {
    console.error("bench/PACKS.md is stale; run `node bench/packs.mjs` and commit the result");
    process.exit(1);
  }
  console.log(`pack table up to date (${packCount} packs, ${languages.length} languages)`);
} else {
  writeFileSync(output, md);
  console.log(`wrote bench/PACKS.md (${packCount} packs, ${languages.length} languages)`);
}
